    def 填充遮罩孔洞(self, 遮罩_np):
        """填充遮罩内部的孔洞"""
        from scipy import ndimage

        # 二值化遮罩
        二值遮罩 = 遮罩_np > 0.1

        # 使用形态学操作填充孔洞
        填充遮罩 = ndimage.binary_fill_holes(二值遮罩)

        # 转换回原始范围
        填充遮罩 = 填充遮罩.astype(np.float32)

        return 填充遮罩

    def 计算倍数取整(self, 值, 倍数):
        """向下取整，用于自定义宽高模式"""
        if 倍数 <= 1:
            return 值
        return math.floor(值 / 倍数) * 倍数

    def 计算倍数取整_向上(self, 值, 倍数):
        """向上取整，确保输出尺寸不小于实际所需尺寸，多余部分由边缘颜色填充"""
        if 倍数 <= 1:
            return 值
        return math.ceil(值 / 倍数) * 倍数

    def 获取颜色众数(self, 图像, 区域, 方向, 采样宽度=10):
        """获取指定区域边缘颜色的众数（出现频率最高的颜色）"""
        if 图像.mode != "RGB":
            图像 = 图像.convert("RGB")

        宽, 高 = 图像.size
        左, 上, 右, 下 = 区域

        # 定义采样区域
        if 方向 == "左" and 左 < 0:
            # 取最左侧的一列像素进行采样
            采样左 = 0
            采样右 = min(采样宽度, 宽)
            采样上 = max(0, 上)
            采样下 = min(高, 下)
        elif 方向 == "右" and 右 > 宽:
            # 取最右侧的一列像素进行采样
            采样右 = 宽
            采样左 = max(0, 宽 - 采样宽度)
            采样上 = max(0, 上)
            采样下 = min(高, 下)
        elif 方向 == "上" and 上 < 0:
            # 取最上方的一行像素进行采样
            采样上 = 0
            采样下 = min(采样宽度, 高)
            采样左 = max(0, 左)
            采样右 = min(宽, 右)
        elif 方向 == "下" and 下 > 高:
            # 取最下方的一行像素进行采样
            采样下 = 高
            采样上 = max(0, 高 - 采样宽度)
            采样左 = max(0, 左)
            采样右 = min(宽, 右)
        else:
            # 不需要填充或方向无效，返回黑色
            return (0, 0, 0)

        # 提取采样区域的像素
        if 采样右 > 采样左 and 采样下 > 采样上:
            采样区域 = 图像.crop((采样左, 采样上, 采样右, 采样下))
            像素数据 = list(采样区域.getdata())

            if 像素数据:
                # 对颜色进行量化（将相近颜色归为一类）
                量化像素 = []
                for r, g, b in 像素数据:
                    # 将颜色量化为16级，减少颜色种类
                    量化_r = (r // 16) * 16
                    量化_g = (g // 16) * 16
                    量化_b = (b // 16) * 16
                    量化像素.append((量化_r, 量化_g, 量化_b))

                # 计算众数颜色
                颜色计数 = Counter(量化像素)
                众数颜色 = 颜色计数.most_common(1)[0][0]
                return 众数颜色

        return (0, 0, 0)

    def 获取边缘像素填充图像(self, 图像, 目标区域, 原始宽, 原始高, is_mask=False):
        """使用众数颜色进行填充，每个需要填充的方向都使用该方向的边缘众数颜色填充"""
        左, 上, 右, 下 = 目标区域

        # 计算实际需要的尺寸
        目标宽 = 右 - 左
        目标高 = 下 - 上

        # 创建目标图像
        if is_mask:
            # 对于遮罩，超出部分始终用黑色填充
            目标图像 = Image.new("L", (目标宽, 目标高), 0)
        else:
            # 对于图像，使用原图模式
            目标图像 = Image.new(图像.mode, (目标宽, 目标高))

            # 预计算各方向的众数颜色
            左众数 = self.获取颜色众数(图像, (左, 上, 右, 下), "左")
            右众数 = self.获取颜色众数(图像, (左, 上, 右, 下), "右")
            上众数 = self.获取颜色众数(图像, (左, 上, 右, 下), "上")
            下众数 = self.获取颜色众数(图像, (左, 上, 右, 下), "下")

        # 计算在原始图像内的有效区域
        有效左 = max(0, 左)
        有效上 = max(0, 上)
        有效右 = min(原始宽, 右)
        有效下 = min(原始高, 下)

        # 计算在目标图像中的对应位置
        目标左偏移 = 有效左 - 左
        目标上偏移 = 有效上 - 上

        # 如果有有效区域，从原图复制
        if 有效右 > 有效左 and 有效下 > 有效上:
            有效区域 = 图像.crop((有效左, 有效上, 有效右, 有效下))
            目标图像.paste(有效区域, (目标左偏移, 目标上偏移))

        # 对于图像，使用众数颜色填充超出边界的部分
        if not is_mask:
            # 判断需要填充的方向（每个方向独立判断，不再限制只填充一个方向）
            需要填充左 = 左 < 0
            需要填充右 = 右 > 原始宽
            需要填充上 = 上 < 0
            需要填充下 = 下 > 原始高

            # 左侧填充
            if 需要填充左:
                填充宽度 = -左
                for x in range(填充宽度):
                    for y in range(目标高):
                        目标图像.putpixel((x, y), 左众数)

            # 右侧填充
            if 需要填充右:
                填充宽度 = 右 - 原始宽
                起始x = 目标宽 - 填充宽度
                for x in range(起始x, 目标宽):
                    for y in range(目标高):
                        目标图像.putpixel((x, y), 右众数)

            # 上方填充
            if 需要填充上:
                填充高度 = -上
                for y in range(填充高度):
                    for x in range(目标宽):
                        目标图像.putpixel((x, y), 上众数)

            # 下方填充
            if 需要填充下:
                填充高度 = 下 - 原始高
                起始y = 目标高 - 填充高度
                for y in range(起始y, 目标高):
                    for x in range(目标宽):
                        目标图像.putpixel((x, y), 下众数)

        return 目标图像

    def 裁剪图像(self, 图像, 遮罩, 遮罩填充, 扩展系数上, 扩展系数下, 扩展系数左, 扩展系数右,
                  输出尺寸, 自定义宽, 自定义高, 倍数取整):
        # 确保输入是单张图像
        if 图像.shape[0] > 1:
            图像 = 图像[0:1]
        if 遮罩.shape[0] > 1:
            遮罩 = 遮罩[0:1]

        # 转换tensor为numpy数组
        图像_np = 图像[0].cpu().numpy()
        遮罩_np = 遮罩[0].cpu().numpy()

        原始高, 原始宽 = 图像_np.shape[:2]
        有效区域 = (遮罩_np > 0.1).astype(np.uint8)
        if cv2.countNonZero(有效区域):
            _, 连通标签, 连通统计, _ = cv2.connectedComponentsWithStats(有效区域, connectivity=8)
            最大连通面积 = int(连通统计[1:, cv2.CC_STAT_AREA].max())
            del 连通标签
        else:
            最大连通面积 = 0
        # 在填孔和裁剪前替换，接缝中保存的原始遮罩也必须是这张全白遮罩。
        if 最大连通面积 < 原始高 * 原始宽 * 0.002:
            遮罩 = torch.ones((1, 原始高, 原始宽), dtype=遮罩.dtype, device=遮罩.device)
            遮罩_np = 遮罩[0].cpu().numpy()

        # 保存填充后的遮罩到接缝数据
        填充后遮罩_np = 遮罩_np.copy()

        # 根据遮罩填充开关处理遮罩
        if 遮罩填充:
            填充后遮罩_np = self.填充遮罩孔洞(遮罩_np)

        # 找到遮罩的非零区域边界（使用填充后的遮罩）
        非零区域 = np.where(填充后遮罩_np > 0.1)  # 使用阈值避免噪点
        最小y, 最大y = np.min(非零区域[0]), np.max(非零区域[0])
        最小x, 最大x = np.min(非零区域[1]), np.max(非零区域[1])
        # np.max返回的是最大索引(0-based)，实际尺寸需要+1
        遮罩宽 = 最大x - 最小x + 1
        遮罩高 = 最大y - 最小y + 1

        # 计算遮罩最短边
        遮罩最短边 = min(遮罩宽, 遮罩高)

        # 计算四个方向的扩展量（分别乘以遮罩最短边像素值*(扩展系数-1)）
        扩展量上 = int(遮罩最短边 * (扩展系数上 - 1.0))
        扩展量下 = int(遮罩最短边 * (扩展系数下 - 1.0))
        扩展量左 = int(遮罩最短边 * (扩展系数左 - 1.0))
        扩展量右 = int(遮罩最短边 * (扩展系数右 - 1.0))

        # 限制扩展量不超过原图边界
        扩展量上 = min(扩展量上, 最小y)  # 向上扩展不能超过图像顶部
        扩展量下 = min(扩展量下, 原始高 - 最大y - 1)  # 向下扩展不能超过图像底部
        扩展量左 = min(扩展量左, 最小x)  # 向左扩展不能超过图像左侧
        扩展量右 = min(扩展量右, 原始宽 - 最大x - 1)  # 向右扩展不能超过图像右侧

        # 计算基础裁剪区域（遮罩区域 + 各方向扩展量）
        基础顶部 = 最小y - 扩展量上
        基础底部 = 最大y + 1 + 扩展量下
        基础左侧 = 最小x - 扩展量左
        基础右侧 = 最大x + 1 + 扩展量右

        # 根据输出尺寸选项确定最终裁剪区域
        if 输出尺寸 == "原像素":
            # 原像素：遮罩+扩展量，然后倍数取整
            裁剪宽 = 基础右侧 - 基础左侧
            裁剪高 = 基础底部 - 基础顶部

            if 倍数取整 > 1:
                # 向上取整，确保不裁掉像素，多余的由边缘颜色填充
                裁剪宽 = self.计算倍数取整_向上(裁剪宽, 倍数取整)
                裁剪高 = self.计算倍数取整_向上(裁剪高, 倍数取整)

            # 保持中心点不变，调整尺寸
            中心x = (基础左侧 + 基础右侧) // 2
            中心y = (基础顶部 + 基础底部) // 2

            最终左侧 = 中心x - 裁剪宽 // 2
            最终右侧 = 最终左侧 + 裁剪宽
            最终顶部 = 中心y - 裁剪高 // 2
            最终底部 = 最终顶部 + 裁剪高

        elif 输出尺寸 == "原像素1：1":
            # 原像素1：1：取最小外接正方形，然后倍数取整
            基础宽 = 基础右侧 - 基础左侧
            基础高 = 基础底部 - 基础顶部
            目标尺寸 = max(基础宽, 基础高)

            if 倍数取整 > 1:
                目标尺寸 = self.计算倍数取整_向上(目标尺寸, 倍数取整)

            # 保持中心点不变，调整尺寸
            中心x = (基础左侧 + 基础右侧) // 2
            中心y = (基础顶部 + 基础底部) // 2

            最终左侧 = 中心x - 目标尺寸 // 2
            最终右侧 = 最终左侧 + 目标尺寸
            最终顶部 = 中心y - 目标尺寸 // 2
            最终底部 = 最终顶部 + 目标尺寸

        else:  # 自定义宽高
            # 计算扩展后的遮罩矩形框宽高
            基础宽 = 基础右侧 - 基础左侧
            基础高 = 基础底部 - 基础顶部

            # 当一个为0另一个不为0时，不为0的值为长边输出尺寸
            if (自定义宽 == 0 and 自定义高 != 0) or (自定义宽 != 0 and 自定义高 == 0):
                长边尺寸 = 自定义宽 if 自定义宽 != 0 else 自定义高
                if 基础宽 >= 基础高:
                    # 宽为长边
                    目标宽 = 长边尺寸
                    目标高 = int(长边尺寸 * 基础高 / 基础宽)
                else:
                    # 高为长边
                    目标高 = 长边尺寸
                    目标宽 = int(长边尺寸 * 基础宽 / 基础高)
                # 应用倍数取整
                if 倍数取整 > 1:
                    目标宽 = self.计算倍数取整(目标宽, 倍数取整)
                    目标高 = self.计算倍数取整(目标高, 倍数取整)
            else:
                # 原有逻辑：先对用户输入进行倍数取整
                目标宽 = 自定义宽
                目标高 = 自定义高
                if 倍数取整 > 1:
                    目标宽 = self.计算倍数取整(目标宽, 倍数取整)
                    目标高 = self.计算倍数取整(目标高, 倍数取整)

            # 计算基础宽高比和目标宽高比
            基础宽高比 = 基础宽 / 基础高
            目标宽高比 = 目标宽 / 目标高

            # 确定扩展方向
            if 基础宽高比 < 目标宽高比:
                # 需要扩展宽度
                扩展后宽 = int(基础高 * 目标宽高比)
                扩展后高 = 基础高
            else:
                # 需要扩展高度
                扩展后宽 = 基础宽
                扩展后高 = int(基础宽 / 目标宽高比)

            # 保持中心点不变，调整尺寸
            中心x = (基础左侧 + 基础右侧) // 2
            中心y = (基础顶部 + 基础底部) // 2

            最终左侧 = 中心x - 扩展后宽 // 2
            最终右侧 = 最终左侧 + 扩展后宽
            最终顶部 = 中心y - 扩展后高 // 2
            最终底部 = 最终顶部 + 扩展后高

        # 转换为整数坐标
        最终左侧 = int(最终左侧)
        最终右侧 = int(最终右侧)
        最终顶部 = int(最终顶部)
        最终底部 = int(最终底部)

        # 计算实际裁剪尺寸
        裁剪宽 = 最终右侧 - 最终左侧
        裁剪高 = 最终底部 - 最终顶部

        # 转换为PIL图像进行处理
        pil图像 = Image.fromarray((图像_np * 255).astype(np.uint8))
        pil遮罩 = Image.fromarray((填充后遮罩_np * 255).astype(np.uint8))

        # 获取裁剪区域（使用新的填充方法）
        裁剪图像 = self.获取边缘像素填充图像(pil图像, (最终左侧, 最终顶部, 最终右侧, 最终底部), 原始宽, 原始高, is_mask=False)
        裁剪遮罩 = self.获取边缘像素填充图像(pil遮罩, (最终左侧, 最终顶部, 最终右侧, 最终底部), 原始宽, 原始高, is_mask=True)

        # 保存未缩放的裁剪图像和遮罩，用于恢复时计算位置
        未缩放裁剪图像 = 裁剪图像.copy()
        未缩放裁剪遮罩 = 裁剪遮罩.copy()

        # 对于自定义宽高模式，需要等比例缩放到目标尺寸
        if 输出尺寸 == "自定义宽高":
            当前宽, 当前高 = 裁剪图像.size
            缩放比例宽 = 目标宽 / 当前宽
            缩放比例高 = 目标高 / 当前高
            缩放比例 = min(缩放比例宽, 缩放比例高)

            缩放宽 = int(当前宽 * 缩放比例)
            缩放高 = int(当前高 * 缩放比例)

            裁剪图像 = 裁剪图像.resize((缩放宽, 缩放高), Image.LANCZOS)
            裁剪遮罩 = 裁剪遮罩.resize((缩放宽, 缩放高), Image.LANCZOS)

            # 如果需要，填充到目标尺寸
            if 缩放宽 != 目标宽 or 缩放高 != 目标高:
                # 创建目标尺寸图像，用黑色填充
                最终图像 = Image.new(裁剪图像.mode, (目标宽, 目标高), 0)
                最终遮罩 = Image.new(裁剪遮罩.mode, (目标宽, 目标高), 0)

                # 计算粘贴位置（居中）
                左偏移 = (目标宽 - 缩放宽) // 2
                上偏移 = (目标高 - 缩放高) // 2

                最终图像.paste(裁剪图像, (左偏移, 上偏移))
                最终遮罩.paste(裁剪遮罩, (左偏移, 上偏移))

                裁剪图像 = 最终图像
                裁剪遮罩 = 最终遮罩

                # 保存填充信息
                填充信息 = (左偏移, 上偏移, 缩放宽, 缩放高, 目标宽, 目标高)
            else:
                填充信息 = None
        else:
            目标宽, 目标高 = 裁剪图像.size
            填充信息 = None

        # 转换回numpy数组
        最终图像_np = np.array(裁剪图像).astype(np.float32) / 255.0
        最终遮罩_np = np.array(裁剪遮罩).astype(np.float32) / 255.0

        # 转换为tensor
        最终图像_tensor = torch.from_numpy(最终图像_np)[None, ...]
        最终遮罩_tensor = torch.from_numpy(最终遮罩_np)[None, ...]

        # 计算缩放比例（用于恢复）
        if 输出尺寸 == "自定义宽高":
            # 自定义宽高模式下，有两次缩放：从裁剪区域到扩展区域，再到目标尺寸
            原始裁剪宽 = 最终右侧 - 最终左侧
            原始裁剪高 = 最终底部 - 最终顶部
            扩展后宽 = 未缩放裁剪图像.size[0]
            扩展后高 = 未缩放裁剪图像.size[1]

            缩放比例宽 = 扩展后宽 / 原始裁剪宽
            缩放比例高 = 扩展后高 / 原始裁剪高
            最终缩放宽 = 目标宽 / 扩展后宽 if 输出尺寸 == "自定义宽高" else 1.0
            最终缩放高 = 目标高 / 扩展后高 if 输出尺寸 == "自定义宽高" else 1.0
        else:
            # 其他模式下，只有一次缩放：从裁剪区域到目标尺寸
            原始裁剪宽 = 最终右侧 - 最终左侧
            原始裁剪高 = 最终底部 - 最终顶部
            缩放比例宽 = 目标宽 / 原始裁剪宽
            缩放比例高 = 目标高 / 原始裁剪高
            最终缩放宽 = 1.0
            最终缩放高 = 1.0

        # 创建接缝数据（包含所有必要信息）
        接缝数据 = {
            "原始图像": 图像,  # 原始图像tensor
            "原始遮罩": 遮罩,    # 原始遮罩tensor
            "填充后遮罩": torch.from_numpy(填充后遮罩_np)[None, ...],
            "原像素": (原始高, 原始宽),
            "裁剪区域": (最终顶部, 最终底部, 最终左侧, 最终右侧),
            "目标尺寸": (目标高, 目标宽),
            "缩放比例宽": 缩放比例宽,
            "缩放比例高": 缩放比例高,
            "最终缩放宽": 最终缩放宽,
            "最终缩放高": 最终缩放高,
            "输出尺寸模式": 输出尺寸,
            "填充信息": 填充信息,  # 保存填充信息用于恢复
            "遮罩填充": 遮罩填充,
            "遮罩白色区域宽": 遮罩宽,
            "遮罩白色区域高": 遮罩高,
            "未缩放裁剪遮罩": 未缩放裁剪遮罩  # 保存未缩放的裁剪遮罩用于恢复
        }

        return (接缝数据, 最终图像_tensor, 最终遮罩_tensor)


