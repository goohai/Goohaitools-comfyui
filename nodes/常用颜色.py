自定义标识 = "自定义"


class 常用颜色孤海:
    """
    常用颜色🔵孤海
    从预设颜色中选取，或通过取色器自定义颜色，
    输出十六进制颜色字符串（如 #FFFFFF）。
    """

    @classmethod
    def INPUT_TYPES(cls):
        # 下拉菜单：预设颜色名称 + "自定义"
        颜色选项列表 = list(颜色预设.keys()) + [自定义标识]

        return {
            "required": {
                "选择颜色": (颜色选项列表, {"default": 颜色选项列表[0]}),
            },
            "optional": {
                "自定义颜色": ("COLORCODE", {"default": "#242730"}),
            },
        }

    # 节点输出类型
    RETURN_TYPES = ("STRING",)
    RETURN_NAMES = ("T",)
    FUNCTION = "获取颜色"
    CATEGORY = "🔵孤海/常用工具"
    OUTPUT_NODE = False

    def 获取颜色(self, 选择颜色, 自定义颜色="#213D50"):
        if 选择颜色 == 自定义标识:
            # 使用取色器的值
            颜色结果 = self.规范化颜色(自定义颜色)
        else:
            # 从预设字典中取值
            颜色结果 = 颜色预设.get(选择颜色, "#000000")

        return (颜色结果,)

    @staticmethod
    def 规范化颜色(颜色值):
        """确保颜色值为 #RRGGBB 格式"""
        颜色值 = 颜色值.strip()
        if not 颜色值.startswith("#"):
            颜色值 = "#" + 颜色值
        # 处理短格式 #RGB -> #RRGGBB
        if len(颜色值) == 4:
            颜色值 = "#" + 颜色值[1]*2 + 颜色值[2]*2 + 颜色值[3]*2
        return 颜色值.upper()


